// Day 3 - Add Two Numbers

public class Day03_AddTwoNumbers {
    public static void main(String[] args) {

        int num1 = 25;
        int num2 = 15;

        int sum = num1 + num2;

        System.out.println("First Number  : " + num1);
        System.out.println("Second Number : " + num2);
        System.out.println("Sum           : " + sum);
    }
}